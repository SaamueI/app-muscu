#!/usr/bin/env node
/**
 * Generates src/db/exerciseImages.ts — a static require() map for all
 * exercise images. Metro requires static requires for images; dynamic
 * paths like require('./path/' + id) do not work.
 *
 * Run with: node scripts/generate-exercise-images.js
 */

const fs = require('fs');
const path = require('path');

const exercisesJson = path.join(__dirname, '../../free-exercise-db-main/dist/exercises.json');
const assetsDir = path.join(__dirname, '../assets/exercises');
const outputFile = path.join(__dirname, '../src/db/exerciseImages.ts');

const exercises = JSON.parse(fs.readFileSync(exercisesJson, 'utf8'));

const lines = [
  '// Auto-generated by scripts/generate-exercise-images.js — do not edit manually.',
  '// Re-run the script if exercises are added or images change.',
  '',
  'const exerciseImages: Record<string, number[]> = {',
];

for (const exercise of exercises) {
  const images = (exercise.images || []).filter((imgPath) => {
    const fullPath = path.join(assetsDir, imgPath);
    return fs.existsSync(fullPath);
  });

  if (images.length === 0) continue;

  const requires = images
    .map((imgPath) => `    require('../../assets/exercises/${imgPath}'),`)
    .join('\n');

  lines.push(`  '${exercise.id}': [`);
  lines.push(requires);
  lines.push('  ],');
}

lines.push('};', '', 'export default exerciseImages;', '');

fs.writeFileSync(outputFile, lines.join('\n'), 'utf8');
console.log(`Generated ${outputFile}`);
console.log(`Entries: ${lines.filter((l) => l.startsWith("  '")).length} exercises`);
